"""Plan, seal, package, and verify PR1073 validation evidence without source edits.

Default execution only writes a preliminary plan. Use --finalize only after the
parent confirms all evidence files are stable. Capture final execution logs and
command metadata OUTSIDE result_root; no result-root file may change after sealing.
"""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import os
from pathlib import Path
import re
import shlex
import shutil
import stat
import sys
import time
import zipfile

DEFAULT_ROOT = Path('/workspace/TICO/out/pr1073_validation/20261022T0404Z')
DEFAULT_ARCHIVE = Path('/workspace/shared/downloads/TICO_PR1073_validation_20261022T0404Z.zip')
PREFIX = 'TICO_PR1073_validation_20261022T0404Z'
MANIFEST = 'SHA256_MANIFEST.json'
PRODUCER = 'package_validation_artifacts.py'
TRANSIENT_COMPONENTS = {'baseline_mypy_cache', '__pycache__', '.mypy_cache'}
DATASET_CACHE_PREFIX = 'hf_cache'
FIXED_ZIP_TIME = (2026, 10, 22, 4, 4, 0)


def now() -> str:
    return dt.datetime.now(dt.timezone.utc).isoformat()


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open('rb') as source:
        for chunk in iter(lambda: source.read(1 << 20), b''):
            digest.update(chunk)
    return digest.hexdigest()


def write_new_metadata(path: Path, value) -> None:
    """Write only package-owned new files, preserving original evidence files."""
    if path.exists():
        if path.suffix == '.json':
            previous = json.loads(path.read_text())
            if previous.get('generated_by') != PRODUCER:
                raise FileExistsError(f'Refusing to overwrite non-package metadata: {path}')
        elif not path.read_text().startswith('# Generated by ' + PRODUCER):
            raise FileExistsError(f'Refusing to overwrite an original evidence file: {path}')
    if path.suffix == '.json':
        path.write_text(json.dumps(value, ensure_ascii=False, allow_nan=False, indent=2) + '\n')
    else:
        path.write_text(value)


def exclusion_reason(relative: Path) -> str | None:
    for component in relative.parts:
        if component in TRANSIENT_COMPONENTS:
            return f'Transient generated cache component: {component}'
    if relative.parts and relative.parts[0] == DATASET_CACHE_PREFIX:
        return 'HF datasets cache; provenance and selected evaluation row evidence are preserved separately'
    return None


def inventory(root: Path, archive: Path):
    included, excluded = [], []
    for directory, names, files in os.walk(root, followlinks=False):
        base = Path(directory)
        for name in names:
            path = base / name
            if path.is_symlink() and exclusion_reason(path.relative_to(root)) is None:
                raise RuntimeError(f'Unexpected directory symlink requires explicit review: {path}')
        for name in files:
            path = base / name
            relative = path.relative_to(root)
            reason = exclusion_reason(relative)
            if reason:
                excluded.append({'path': relative.as_posix(), 'bytes': path.stat().st_size, 'reason': reason})
                continue
            if path.resolve() == archive.resolve():
                excluded.append({'path': relative.as_posix(), 'bytes': path.stat().st_size, 'reason': 'Output archive is excluded to avoid recursive packaging'})
                continue
            if path.is_symlink():
                raise RuntimeError(f'Unexpected file symlink requires explicit review: {path}')
            if not path.is_file():
                raise RuntimeError(f'Non-regular artifact requires explicit handling: {path}')
            if relative.as_posix() != MANIFEST:
                included.append(path)
    return sorted(included), sorted(excluded, key=lambda item: item['path'])


def dataset_evidence(root: Path) -> None:
    """Retain cache provenance and actual first-12 test rows without the cache."""
    cache = root / DATASET_CACHE_PREFIX
    records = []
    dataset_infos = []
    if cache.exists():
        for path in sorted(cache.rglob('*')):
            if not path.is_file():
                continue
            if path.is_symlink():
                raise RuntimeError(f'Unexpected dataset-cache symlink: {path}')
            if path.suffix in {'.safetensors', '.pt', '.pth', '.bin'}:
                raise RuntimeError(f'HF cache contains model/checkpoint assets that must not be excluded: {path}')
            records.append({'path': path.relative_to(root).as_posix(), 'bytes': path.stat().st_size, 'sha256': sha256(path)})
            if path.name == 'dataset_info.json':
                dataset_infos.append({'path': path.relative_to(root).as_posix(), 'metadata': json.loads(path.read_text())})
    protocol_path = root / 'pretrained_fp_cli/evaluation_protocol.json'
    protocol = json.loads(protocol_path.read_text()) if protocol_path.exists() else {}
    evaluation = protocol.get('evaluation', {})
    ppl = evaluation.get('perplexity') or {}
    split = ppl.get('split')
    samples = {'generated_by': PRODUCER, 'result_root': str(root), 'scope': 'Previously cached evaluation data rows; packaging does not rerun evaluation or calibration', 'protocol_path': str(protocol_path.relative_to(root)), 'evaluation_perplexity': ppl, 'rows': [], 'status': 'NO_MATCHING_PROTOCOL_OR_CACHE'}
    match = re.fullmatch(r'([A-Za-z_]+)\[:(\d+)\]', split or '')
    if match and cache.exists():
        split_name, limit = match.group(1), int(match.group(2))
        candidates = sorted(cache.rglob(f'*-{split_name}.arrow'))
        if len(candidates) != 1:
            raise RuntimeError(f'Expected exactly one cached {split_name} Arrow file, found {len(candidates)}')
        import pyarrow as pa
        import pyarrow.ipc as ipc
        selected = []
        with pa.memory_map(str(candidates[0]), 'r') as source:
            reader = ipc.open_stream(source)
            for batch in reader:
                selected.extend(batch.slice(0, max(0, limit - len(selected))).to_pylist())
                if len(selected) >= limit:
                    break
        if len(selected) != limit:
            raise RuntimeError(f'Cached sample evidence incomplete: {len(selected)} != {limit}')
        samples.update({'status': 'CAPTURED', 'source_arrow': candidates[0].relative_to(root).as_posix(), 'source_arrow_sha256': sha256(candidates[0]), 'source_schema': str(batch.schema), 'selected_row_count': limit, 'rows': [{'dataset_row_index': index, 'row': row, 'row_json_sha256': hashlib.sha256(json.dumps(row, ensure_ascii=False, sort_keys=True).encode()).hexdigest()} for index, row in enumerate(selected)]})
    write_new_metadata(root / 'PACKAGE_HF_DATASET_PROVENANCE.json', {'generated_by': PRODUCER, 'result_root': str(root), 'generated_at': now(), 'excluded_cache_root': DATASET_CACHE_PREFIX, 'cache_files': records, 'dataset_info': dataset_infos, 'sample_evidence': 'PACKAGE_HF_TEST_SAMPLES.json', 'note': 'Original protocol, metrics, sample IDs, tokenizer/input hashes and logs remain included as separate evidence'})
    write_new_metadata(root / 'PACKAGE_HF_TEST_SAMPLES.json', samples)


def verify_archive(archive: Path) -> dict:
    with zipfile.ZipFile(archive) as bundle:
        manifest_name = PREFIX + '/' + MANIFEST
        manifest = json.loads(bundle.read(manifest_name))
        expected = {PREFIX + '/' + item['path']: item for item in manifest['files']}
        actual = {item.filename for item in bundle.infolist() if not item.is_dir()}
        if actual != set(expected) | {manifest_name}:
            raise AssertionError('Archive entry inventory differs from the manifest')
        for name, item in expected.items():
            digest = hashlib.sha256()
            size = 0
            with bundle.open(name) as source:
                for chunk in iter(lambda: source.read(1 << 20), b''):
                    size += len(chunk)
                    digest.update(chunk)
            if size != item['bytes'] or digest.hexdigest() != item['sha256']:
                raise AssertionError(f'Archive checksum mismatch: {name}')
        return {'status': 'VERIFIED', 'files_verified': len(expected), 'manifest_sha256': hashlib.sha256(bundle.read(manifest_name)).hexdigest()}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--result-root', type=Path, default=DEFAULT_ROOT)
    parser.add_argument('--archive', type=Path, default=DEFAULT_ARCHIVE)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument('--plan', action='store_true')
    modes.add_argument('--finalize', action='store_true')
    modes.add_argument('--verify-archive', type=Path)
    args = parser.parse_args()
    if args.verify_archive:
        result = verify_archive(args.verify_archive.resolve())
        print(json.dumps(result))
        return 0
    root, archive = args.result_root.resolve(), args.archive.resolve()
    if not root.is_dir():
        parser.error('Result root must already exist')
    if archive.is_relative_to(root):
        parser.error('Place the output archive outside result_root to prevent recursion')
    files, excluded = inventory(root, archive)
    if not args.finalize:
        plan = {'generated_by': PRODUCER, 'result_root': str(root), 'generated_at': now(), 'status': 'PRELIMINARY_PLAN_NOT_PACKAGED', 'archive': str(archive), 'included_file_count_now': len(files), 'included_bytes_now': sum(path.stat().st_size for path in files), 'excluded_file_count_now': len(excluded), 'excluded_bytes_now': sum(item['bytes'] for item in excluded), 'exclusions_now': excluded, 'rules': sorted(TRANSIENT_COMPONENTS) + [DATASET_CACHE_PREFIX], 'retained': ['all raw logs, command records, scripts, configs, Circle/NPZ/PNG artifacts', 'all checkpoints and selected pretrained assets', 'invalid/failed first-run evidence and script versions'], 'finalize_only_after_parent_signal': True, 'manifest': MANIFEST, 'final_execution_record_location': str(archive) + '.package.json', 'warning': 'Capture final packaging execution logs outside result_root; do not use a logger that mutates result_root after sealing'}
        write_new_metadata(root / 'PACKAGE_PLAN.json', plan)
        print(json.dumps({key: value for key, value in plan.items() if key != 'exclusions_now'}, ensure_ascii=False))
        return 0
    if archive.exists():
        raise FileExistsError(f'Refusing to overwrite an existing archive: {archive}')
    started, start_clock = now(), time.monotonic()
    dataset_evidence(root)
    files, excluded = inventory(root, archive)
    write_new_metadata(root / 'PACKAGE_EXCLUSIONS.json', {'generated_by': PRODUCER, 'result_root': str(root), 'excluded_paths': excluded, 'manifest_self_exclusion': {'path': MANIFEST, 'reason': 'Manifest excludes its own checksum to avoid recursion; the manifest IS included in the ZIP'}, 'archive_exclusion': {'path': str(archive), 'reason': 'Archive and its execution/checksum records reside outside result_root to avoid recursion'}, 'dataset_cache_derivatives_included': ['PACKAGE_HF_DATASET_PROVENANCE.json', 'PACKAGE_HF_TEST_SAMPLES.json']})
    command = shlex.join([sys.executable, str(Path(__file__).resolve()), '--result-root', str(root), '--archive', str(archive), '--finalize'])
    write_new_metadata(root / 'PACKAGE_REPRO_COMMAND.sh', '# Generated by ' + PRODUCER + '\n#!/usr/bin/env bash\n# Run after all evidence files are final. Capture stdout/stderr outside result_root.\n' + command + '\n')
    write_new_metadata(root / 'PACKAGE_README.md', '# Generated by ' + PRODUCER + '\n\nThe ZIP retains all non-transient result-root files, including raw failures, logs, commands, actual Circle/NPZ/PNG artifacts, checkpoints, and selected pretrained assets. Excluded cache paths and reasons are in PACKAGE_EXCLUSIONS.json. HF cache provenance and the actual cached test[:12] rows are retained in PACKAGE_HF_DATASET_PROVENANCE.json and PACKAGE_HF_TEST_SAMPLES.json.\n\nSHA256_MANIFEST.json hashes every included regular file except itself. The ZIP includes that manifest. Archive checksum and final packaging execution metadata are adjacent to the ZIP, outside result_root, to avoid recursive hashes and post-seal log mutations.\n\nUse commands.sh for validation commands and PACKAGE_REPRO_COMMAND.sh for packaging. Verify the ZIP with:\n\n    python package_validation_artifacts.py --verify-archive ' + str(archive) + '\n')
    files, excluded_after_metadata = inventory(root, archive)
    if excluded_after_metadata != excluded:
        raise RuntimeError('Excluded cache inventory changed during metadata generation')
    records, snapshots = [], {}
    for path in files:
        before = path.stat()
        digest = sha256(path)
        after = path.stat()
        if (before.st_size, before.st_mtime_ns) != (after.st_size, after.st_mtime_ns):
            raise RuntimeError(f'Artifact changed while hashing: {path}')
        relative = path.relative_to(root).as_posix()
        records.append({'path': relative, 'bytes': after.st_size, 'sha256': digest})
        snapshots[relative] = (after.st_size, after.st_mtime_ns)
    manifest = {'generated_by': PRODUCER, 'result_root': str(root), 'generated_at': now(), 'hash_algorithm': 'SHA256', 'scope': 'Every non-transient regular result-root file except this manifest and the external archive', 'file_count': len(records), 'total_bytes': sum(item['bytes'] for item in records), 'files': records, 'exclusions_file': 'PACKAGE_EXCLUSIONS.json', 'manifest_self_hashed': False}
    write_new_metadata(root / MANIFEST, manifest)
    archive.parent.mkdir(parents=True, exist_ok=True)
    temporary = archive.with_name(archive.name + f'.partial.{os.getpid()}')
    if temporary.exists():
        raise FileExistsError(temporary)
    published = False
    try:
        with zipfile.ZipFile(temporary, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=6, allowZip64=True) as bundle:
            for item in records + [{'path': MANIFEST, 'bytes': (root / MANIFEST).stat().st_size, 'sha256': sha256(root / MANIFEST)}]:
                path = root / item['path']
                entry = zipfile.ZipInfo(PREFIX + '/' + item['path'], date_time=FIXED_ZIP_TIME)
                entry.compress_type = zipfile.ZIP_DEFLATED
                entry.create_system = 3
                entry.external_attr = (stat.S_IFREG | 0o644) << 16
                digest, size = hashlib.sha256(), 0
                with path.open('rb') as source, bundle.open(entry, 'w', force_zip64=True) as target:
                    for chunk in iter(lambda: source.read(1 << 20), b''):
                        target.write(chunk)
                        digest.update(chunk)
                        size += len(chunk)
                if size != item['bytes'] or digest.hexdigest() != item['sha256']:
                    raise RuntimeError(f'Artifact changed while archiving: {path}')
        current_files, current_exclusions = inventory(root, archive)
        if {path.relative_to(root).as_posix() for path in current_files} != set(snapshots) or current_exclusions != excluded:
            raise RuntimeError('Result-root inventory changed after sealing')
        for relative, expected_stat in snapshots.items():
            current_stat = (root / relative).stat()
            if (current_stat.st_size, current_stat.st_mtime_ns) != expected_stat:
                raise RuntimeError(f'Artifact metadata changed after sealing: {relative}')
        verification = verify_archive(temporary)
        os.replace(temporary, archive)
        published = True
        archive_digest = sha256(archive)
        external = {'generated_by': PRODUCER, 'status': 'PACKAGED_AND_VERIFIED', 'started_at': started, 'finished_at': now(), 'elapsed_seconds': time.monotonic() - start_clock, 'command': command, 'cwd': str(Path.cwd()), 'exit_code': 0, 'result_root': str(root), 'archive': str(archive), 'archive_bytes': archive.stat().st_size, 'archive_sha256': archive_digest, 'included_file_count': len(records), 'included_total_bytes': manifest['total_bytes'], 'excluded_file_count': len(excluded), 'excluded_total_bytes': sum(item['bytes'] for item in excluded), 'verification': verification}
        archive.with_suffix(archive.suffix + '.package.json').write_text(json.dumps(external, indent=2) + '\n')
        archive.with_suffix(archive.suffix + '.sha256').write_text(archive_digest + '  ' + archive.name + '\n')
        print(json.dumps(external))
        return 0
    finally:
        if not published and temporary.exists():
            temporary.unlink()


if __name__ == '__main__':
    raise SystemExit(main())
